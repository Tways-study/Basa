import { execFileSync } from "node:child_process";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { PAGE_H, PAGE_W, fontsOf, renderChart } from "./render";
import { SPECS, buildManifest, truthOf, type ChartSpec } from "./specs";

// pnpm eval:charts              render every chart, write the truth JSON, rewrite eval/manifest.json
// pnpm eval:charts --ids=a,b    render only these charts (the manifest is still rewritten from all specs)
// pnpm eval:charts --sheet      also write eval/runs/contact-sheet.jpg to look at every chart at once
// Needs the macOS fonts the specs name. The images are committed, so only regenerating needs them.

const ROOT = process.cwd();

function installedFonts(): Set<string> | null {
  try {
    const out = execFileSync("fc-list", [":", "family"], { encoding: "utf8" });
    return new Set(out.split("\n").flatMap((line) => line.split(",").map((f) => f.trim())));
  } catch {
    return null; // no fc-list: skip the check and let the render show what is wrong
  }
}

async function main() {
  const args = process.argv.slice(2);
  const ids = args.find((a) => a.startsWith("--ids="))?.slice(6).split(",");
  const wantSheet = args.includes("--sheet");

  const chosen: ChartSpec[] = ids ? SPECS.filter((s) => ids.includes(s.id)) : SPECS;
  if (ids && chosen.length !== ids.length) throw new Error(`Unknown chart id in --ids=${ids.join(",")}`);

  const fonts = installedFonts();
  if (fonts) {
    const missing = [...new Set(chosen.flatMap(fontsOf))].filter((f) => !fonts.has(f));
    if (missing.length) throw new Error(`These fonts are not installed: ${missing.join(", ")}`);
  }

  const dir = path.join(ROOT, "eval/fixtures");
  await mkdir(dir, { recursive: true });
  const rendered: { id: string; jpeg: Buffer }[] = [];
  for (const spec of chosen) {
    const jpeg = await renderChart(spec);
    const truth = {
      ...truthOf(spec),
      _image: { width: PAGE_W, height: PAGE_H },
      _features: spec.features,
      _note: `Generated by eval/charts (${spec.hard ? "hard" : "easy"}, ${spec.split}). ${spec.note} Synthetic: every name and value is fictional.`,
    };
    await writeFile(path.join(dir, `${spec.id}.jpg`), jpeg);
    await writeFile(path.join(dir, `${spec.id}.json`), JSON.stringify(truth, null, 2) + "\n");
    rendered.push({ id: spec.id, jpeg });
    console.log(`${spec.id}  ${spec.split}  ${spec.hard ? "hard" : "easy"}  ${spec.features.join(", ") || "clean"}`);
  }

  const manifest = {
    note: "Charts for the eval. split: dev is for tuning prompts; test is held out and run once with --final. hard marks charts built to make readers disagree. All charts are synthetic. A phone photo replaces a generated chart by changing its file here and adding truth: eval/fixtures/<id>.json.",
    charts: buildManifest(),
  };
  await writeFile(path.join(ROOT, "eval/manifest.json"), JSON.stringify(manifest, null, 2) + "\n");
  console.log(`Wrote eval/manifest.json (${manifest.charts.length} charts)`);

  if (wantSheet) {
    const cols = 5;
    const w = 330;
    const h = Math.round((w * PAGE_H) / PAGE_W);
    const rows = Math.ceil(rendered.length / cols);
    const tiles = await Promise.all(
      rendered.map(async (r, i) => ({
        input: await sharp(r.jpeg).resize(w, h).toBuffer(),
        left: (i % cols) * w,
        top: Math.floor(i / cols) * h,
      })),
    );
    const out = path.join(ROOT, "eval/runs/contact-sheet.jpg");
    await mkdir(path.dirname(out), { recursive: true });
    await sharp({ create: { width: cols * w, height: rows * h, channels: 3, background: "#222" } })
      .composite(tiles)
      .jpeg({ quality: 80 })
      .toFile(out);
    console.log(`Wrote ${path.relative(ROOT, out)}`);
  }
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});
